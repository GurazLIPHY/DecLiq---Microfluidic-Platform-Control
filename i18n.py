def set_langue(lang: str):
    global LANGUE_ACTUELLE
    if lang in TRADUCTIONS:
        LANGUE_ACTUELLE = lang


def get_langue() -> str:
    return LANGUE_ACTUELLE


def tr(cle: str, default: str = None, **kwargs) -> str:
    dico = TRADUCTIONS.get(LANGUE_ACTUELLE, TRADUCTIONS["fr"])
    txt = dico.get(cle, default if default is not None else cle)
    if kwargs:
        try:
            return txt.format(**kwargs)
        except Exception:
            return txt
    return txt